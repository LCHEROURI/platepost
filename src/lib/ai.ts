import { auth, isFirebaseConfigured } from './firebase';
import { uid } from './utils';
import type { AiSuggestion, PostCategory, Tone } from './types';

/** Read at call time so env changes (and tests) take effect. */
function getServiceUrl(): string | undefined {
  return import.meta.env.VITE_AI_SERVICE_URL;
}

export class AiServiceError extends Error {
  constructor(message: string) {
    super(message);
    this.name = 'AiServiceError';
  }
}

export interface GenerateCaptionsInput {
  restaurantName: string;
  category: PostCategory;
  keywords: string[];
  tone: Tone;
}

/**
 * Real AI captions, generated by Gemini through the PlatePost Cloud Run service
 * (functions/ai). The browser sends the Firebase ID token; the service verifies
 * it and calls Gemini server-side. There is no mock fallback — if the service is
 * unavailable the caller gets an error and the UI shows a clear message.
 */
export async function generateCaptions(input: GenerateCaptionsInput): Promise<AiSuggestion[]> {
  const serviceUrl = getServiceUrl();
  if (!serviceUrl) {
    throw new AiServiceError(
      "AI captions aren't configured yet. Set VITE_AI_SERVICE_URL to the Cloud Run service URL.",
    );
  }
  if (!isFirebaseConfigured || !auth) {
    throw new AiServiceError(
      "AI captions aren't available in demo mode. Configure Firebase and the AI service first.",
    );
  }

  const currentUser = auth.currentUser;
  const idToken = currentUser ? await currentUser.getIdToken() : null;
  if (!idToken) {
    throw new AiServiceError('Sign in to generate AI captions.');
  }

  let res: Response;
  try {
    res = await fetch(`${serviceUrl.replace(/\/+$/, '')}/generate`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json', Authorization: `Bearer ${idToken}` },
      body: JSON.stringify(input),
    });
  } catch {
    throw new AiServiceError('The AI service is unreachable right now. Please try again in a moment.');
  }

  if (!res.ok) {
    throw new AiServiceError('The AI service is unavailable right now. Please try again in a moment.');
  }

  let data: unknown;
  try {
    data = await res.json();
  } catch {
    throw new AiServiceError('The AI service returned an unexpected response. Please try again.');
  }

  const raw = (data as { suggestions?: Array<{ text?: string; caption?: string; hashtags?: unknown[] }> })
    ?.suggestions;
  const suggestions: AiSuggestion[] = (Array.isArray(raw) ? raw : [])
    .map((s) => ({
      id: uid(),
      text: String(s?.text ?? s?.caption ?? '').trim(),
      hashtags: Array.isArray(s?.hashtags)
        ? s.hashtags
            .map((h) => String(h).replace(/^#/, '').trim())
            .filter(Boolean)
            .slice(0, 8)
        : [],
    }))
    .filter((s) => s.text.length > 0)
    .slice(0, 3);

  if (suggestions.length === 0) {
    throw new AiServiceError(
      'No captions could be generated for this draft. Try adjusting your keywords.',
    );
  }

  return suggestions;
}
